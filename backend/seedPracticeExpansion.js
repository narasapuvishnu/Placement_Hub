async function seedPracticeExpansion() {
  try {
    await connectDB();
    for (const [title, topic] of Object.entries(topicUpdates)) {
      await Question.updateOne({ title }, { $set: { topic } });
    }
    for (const question of [...questions, ...aptitude]) {
      await Question.findOneAndUpdate({ title: question.title }, question, { upsert: true, returnDocument: "after" });
      console.log(`Seeded practice question: ${question.title}`);
    }
    console.log(`Seeded ${questions.length + aptitude.length} expanded practice questions.`);
    process.exit(0);
  } catch (error) {
    console.error("Practice expansion seed failed:", error);
    process.exit(1);
  }
}

seedPracticeExpansion();
